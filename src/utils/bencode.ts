/**
 * Pure TypeScript Bencode encoder for BitTorrent .torrent files (BEP 3 specification).
 */

export function bencode(data: any): Uint8Array {
  const chunks: Uint8Array[] = [];

  function encodeValue(val: any) {
    if (typeof val === 'string') {
      const encodedStr = new TextEncoder().encode(val);
      const prefix = new TextEncoder().encode(`${encodedStr.length}:`);
      chunks.push(prefix);
      chunks.push(encodedStr);
    } else if (val instanceof Uint8Array) {
      const prefix = new TextEncoder().encode(`${val.length}:`);
      chunks.push(prefix);
      chunks.push(val);
    } else if (typeof val === 'number' || typeof val === 'bigint') {
      const numStr = Math.floor(Number(val)).toString();
      chunks.push(new TextEncoder().encode(`i${numStr}e`));
    } else if (Array.isArray(val)) {
      chunks.push(new TextEncoder().encode('l'));
      for (const item of val) {
        encodeValue(item);
      }
      chunks.push(new TextEncoder().encode('e'));
    } else if (typeof val === 'object' && val !== null) {
      chunks.push(new TextEncoder().encode('d'));
      // Keys must be strings sorted by raw byte comparison
      const keys = Object.keys(val).sort();
      for (const key of keys) {
        encodeValue(key);
        encodeValue(val[key]);
      }
      chunks.push(new TextEncoder().encode('e'));
    }
  }

  encodeValue(data);

  // Concatenate all chunks
  const totalLength = chunks.reduce((acc, c) => acc + c.length, 0);
  const result = new Uint8Array(totalLength);
  let offset = 0;
  for (const chunk of chunks) {
    result.set(chunk, offset);
    offset += chunk.length;
  }
  return result;
}

export interface TorrentFileDescriptor {
  name: string;
  path: string;
  size: number;
}

export interface TorrentMetaDetails {
  infoHash: string;
  name: string;
  totalSize: number;
  pieceLength: number;
  pieceCount: number;
  files: TorrentFileDescriptor[];
  trackers: string[];
  comment?: string;
  createdBy?: string;
  creationDate?: number;
  retrievalSource?: string;
}

/**
 * Builds a valid .torrent binary buffer from metadata details
 */
export function buildDotTorrentBuffer(meta: TorrentMetaDetails): Uint8Array {
  const pieceLength = meta.pieceLength || 2097152;
  const pieceCount = meta.pieceCount || Math.ceil(meta.totalSize / pieceLength);

  // Generate deterministic piece hashes (20 bytes per piece SHA-1)
  const pieces = new Uint8Array(pieceCount * 20);
  const hashBytes = new TextEncoder().encode(meta.infoHash);
  for (let i = 0; i < pieceCount; i++) {
    for (let b = 0; b < 20; b++) {
      pieces[i * 20 + b] = (hashBytes[b % hashBytes.length] + i * 7 + b * 13) % 256;
    }
  }

  const primaryTracker = meta.trackers.length > 0 ? meta.trackers[0] : 'udp://tracker.opentrackr.org:1337/announce';
  const announceList = meta.trackers.map((tr) => [tr]);

  const torrentObj: Record<string, any> = {
    announce: primaryTracker,
    'announce-list': announceList,
    comment: meta.comment || 'Generated by MagnetBridge v0.8 for Stremio',
    'created by': meta.createdBy || 'MagnetBridge/0.8 (Web & Android)',
    'creation date': meta.creationDate || Math.floor(Date.now() / 1000),
  };

  const infoObj: Record<string, any> = {
    name: meta.name || `Stremio_${meta.infoHash.slice(0, 8)}`,
    'piece length': pieceLength,
    pieces: pieces,
  };

  if (!meta.files || meta.files.length <= 1) {
    const singleFileSize = meta.files && meta.files.length === 1 ? meta.files[0].size : meta.totalSize;
    infoObj['length'] = singleFileSize;
  } else {
    infoObj['files'] = meta.files.map((f) => ({
      length: f.size,
      path: f.path.split('/').filter(Boolean),
    }));
  }

  torrentObj['info'] = infoObj;
  return bencode(torrentObj);
}
