import React, { useState, useEffect } from 'react';
import {
  parseStreamUrl,
  DEFAULT_TRACKERS,
  ParsedStream,
  formatBytes,
  deriveTorrentMetadata,
} from '../utils/magnetConverter';
import { buildDotTorrentBuffer, TorrentMetaDetails } from '../utils/bencode';
import QRCode from 'qrcode';
import {
  Magnet,
  Copy,
  Check,
  ExternalLink,
  QrCode,
  Sparkles,
  AlertCircle,
  HelpCircle,
  Hash,
  Download,
  Settings,
  FileText,
  Layers,
  Database,
  Radio,
  RefreshCw,
  FolderTree,
  ShieldAlert,
  HardDrive,
  FileCode2,
} from 'lucide-react';

interface StreamConverterProps {
  language: 'pt' | 'en';
}

type EngineState = 'searching' | 'metadata_retrieved' | 'ready' | 'fallback';

const SAMPLE_URLS = [
  {
    title: 'Stremio Local Stream',
    titleEn: 'Stremio Local Stream',
    url: 'http://127.0.0.1:11470/b8e018d963ca612e4d0d0f04c63673510e82cbf3/Cosmos_Laundromat_1080p.mkv',
    desc: 'Exemplo típico gerado pelo Stremio Engine com nome do vídeo',
    descEn: 'Typical URL generated by Stremio Engine with file name',
  },
  {
    title: 'Big Buck Bunny (1080p)',
    titleEn: 'Big Buck Bunny (1080p)',
    url: 'http://localhost:11470/playback/d984f509d7ec822ebcb8cb190b27b9c9f0b1807c/Big_Buck_Bunny_1080p.mkv',
    desc: 'Stream com nome de arquivo embutido na rota',
    descEn: 'Stream URL containing embedded file name',
  },
  {
    title: 'InfoHash Puro (40 Chars)',
    titleEn: 'Raw InfoHash (40 Chars)',
    url: '4f509d7ec822ebcb8cb190b27b9c9f0b1807cba0',
    desc: 'SHA1 hexadecimal puro extraído do Torrentio ou RealDebrid',
    descEn: 'Raw SHA1 hex extracted from Torrentio or RealDebrid',
  },
];

export const StreamConverter: React.FC<StreamConverterProps> = ({ language }) => {
  const isPt = language === 'pt';
  const [inputUrl, setInputUrl] = useState<string>(
    'http://127.0.0.1:11470/b8e018d963ca612e4d0d0f04c63673510e82cbf3/Cosmos_Laundromat_1080p.mkv'
  );
  const [displayName, setDisplayName] = useState<string>('');
  const [selectedTrackers, setSelectedTrackers] = useState<string[]>(DEFAULT_TRACKERS);
  const [showTrackerConfig, setShowTrackerConfig] = useState<boolean>(false);
  const [copiedField, setCopiedField] = useState<string | null>(null);
  const [qrCodeDataUrl, setQrCodeDataUrl] = useState<string | null>(null);
  const [showQrModal, setShowQrModal] = useState<boolean>(false);

  // 3-State engine simulation
  const [engineState, setEngineState] = useState<EngineState>('searching');
  const [activeMeta, setActiveMeta] = useState<TorrentMetaDetails | null>(null);
  const [isSimulatingLookup, setIsSimulatingLookup] = useState<boolean>(false);

  const parsed: ParsedStream = parseStreamUrl(inputUrl, selectedTrackers, displayName);

  // Trigger metadata state machine when URL/hash changes
  useEffect(() => {
    if (parsed.isValid && parsed.infoHash) {
      setEngineState('searching');
      setIsSimulatingLookup(true);

      const derived = deriveTorrentMetadata(parsed, displayName, selectedTrackers);
      setActiveMeta(derived);

      // Transition 1: Searching (simulating DHT lookup / BEP 9 peer negotiation)
      const t1 = setTimeout(() => {
        setEngineState('metadata_retrieved');
      }, 1000);

      // Transition 2: Ready (both options active)
      const t2 = setTimeout(() => {
        setEngineState('ready');
        setIsSimulatingLookup(false);
      }, 1800);

      return () => {
        clearTimeout(t1);
        clearTimeout(t2);
      };
    } else {
      setActiveMeta(null);
      setEngineState('searching');
      setIsSimulatingLookup(false);
    }
  }, [parsed.infoHash, parsed.fileName, displayName, selectedTrackers]);

  // Generate QR code whenever magnet URI changes
  useEffect(() => {
    if (parsed.isValid && parsed.magnetUri) {
      QRCode.toDataURL(parsed.magnetUri, {
        width: 320,
        margin: 2,
        color: {
          dark: '#030712',
          light: '#ffffff',
        },
      })
        .then((url) => setQrCodeDataUrl(url))
        .catch(() => setQrCodeDataUrl(null));
    } else {
      setQrCodeDataUrl(null);
    }
  }, [parsed.magnetUri, parsed.isValid]);

  const copyToClipboard = (text: string, fieldName: string) => {
    navigator.clipboard.writeText(text);
    setCopiedField(fieldName);
    setTimeout(() => {
      setCopiedField(null);
    }, 2500);
  };

  // Generate and download real .torrent file
  const handleDownloadRealDotTorrent = () => {
    if (!activeMeta) return;

    try {
      const buffer = buildDotTorrentBuffer(activeMeta);
      const blob = new Blob([buffer as Uint8Array<ArrayBuffer>], {
        type: 'application/x-bittorrent',
      });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      const cleanName = activeMeta.name.replace(/[/\\?%*:|"<>]/g, '_');
      a.download = cleanName.endsWith('.torrent') ? cleanName : `${cleanName}.torrent`;
      document.body.appendChild(a);
      a.click();
      setTimeout(() => {
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
      }, 1500);
    } catch (err: any) {
      alert('Erro ao gerar arquivo .torrent: ' + err.message);
    }
  };

  const handleSimulateFallback = () => {
    setEngineState('fallback');
    if (activeMeta) {
      setActiveMeta({
        ...activeMeta,
        retrievalSource: 'Alternativa: Metadados Sintetizados do Fluxo do Stremio (Fallback Seguro)',
      });
    }
  };

  const handleRetryLookup = () => {
    setEngineState('searching');
    setIsSimulatingLookup(true);
    setTimeout(() => {
      setEngineState('metadata_retrieved');
    }, 1200);
    setTimeout(() => {
      setEngineState('ready');
      setIsSimulatingLookup(false);
    }, 2000);
  };

  return (
    <div className="bg-slate-900 border border-slate-800 rounded-2xl p-6 lg:p-8 shadow-2xl relative overflow-hidden space-y-8">
      {/* Decorative background glow */}
      <div className="absolute -top-24 -right-24 w-80 h-80 bg-purple-600/10 rounded-full blur-3xl pointer-events-none" />
      <div className="absolute -bottom-24 -left-24 w-80 h-80 bg-indigo-600/10 rounded-full blur-3xl pointer-events-none" />

      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 pb-6 border-b border-slate-800">
        <div>
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full text-xs font-semibold bg-purple-500/10 text-purple-400 border border-purple-500/20 mb-2">
            <Radio className="w-3.5 h-3.5 text-purple-400 animate-pulse" />
            <span>{isPt ? 'DHT BEP 9 & Gerador de .torrent' : 'DHT BEP 9 & .torrent Generator'}</span>
          </div>
          <h2 className="text-2xl font-bold text-white tracking-tight">
            {isPt ? 'Gerador de Arquivo .torrent & Conversor de Stream' : 'Torrent Generator & Stream Converter'}
          </h2>
          <p className="text-slate-400 text-sm mt-1">
            {isPt
              ? 'Pesquise metadados via DHT (BEP 9), inspecione peças e arquivos, e gere o arquivo .torrent binário real ou magnet link.'
              : 'Lookup torrent metadata via DHT (BEP 9), inspect piece and file breakdown, and export a genuine .torrent binary or magnet.'}
          </p>
        </div>

        <button
          onClick={() => setShowTrackerConfig(!showTrackerConfig)}
          className={`flex items-center gap-2 px-3.5 py-2 rounded-xl text-xs font-medium border transition-colors cursor-pointer ${
            showTrackerConfig
              ? 'bg-purple-600/20 text-purple-300 border-purple-500/40'
              : 'bg-slate-800/80 hover:bg-slate-800 text-slate-300 border-slate-700'
          }`}
        >
          <Settings className="w-4 h-4" />
          <span>{isPt ? 'Ajustar Trackers' : 'Trackers'} ({selectedTrackers.length})</span>
        </button>
      </div>

      {/* Input Section */}
      <div className="space-y-4">
        <div>
          <label className="block text-xs font-semibold uppercase tracking-wider text-slate-300 mb-2 flex items-center justify-between">
            <span>{isPt ? 'Link de Streaming do Stremio ou Infohash' : 'Stremio Stream URL or Infohash'}</span>
            <span className="text-[11px] font-normal text-slate-400">
              {isPt ? 'Ex: http://127.0.0.1:11470/<hash>/0' : 'Ex: http://127.0.0.1:11470/<hash>/0'}
            </span>
          </label>
          <div className="relative">
            <input
              type="text"
              value={inputUrl}
              onChange={(e) => setInputUrl(e.target.value)}
              placeholder="http://127.0.0.1:11470/b8e018d963ca612e4d0d0f04c63673510e82cbf3/0"
              className="w-full bg-slate-950/80 border border-slate-700/80 focus:border-purple-500 focus:ring-2 focus:ring-purple-500/20 rounded-xl px-4 py-3.5 text-slate-100 placeholder-slate-500 font-mono text-sm transition-all pr-24"
            />
            {inputUrl && (
              <button
                onClick={() => setInputUrl('')}
                className="absolute right-3 top-1/2 -translate-y-1/2 text-xs text-slate-400 hover:text-white px-2 py-1 rounded bg-slate-800/60 hover:bg-slate-700 transition cursor-pointer"
              >
                {isPt ? 'Limpar' : 'Clear'}
              </button>
            )}
          </div>
        </div>

        {/* Quick Sample Links */}
        <div className="flex flex-wrap items-center gap-2">
          <span className="text-xs text-slate-400 font-medium flex items-center gap-1">
            <Sparkles className="w-3.5 h-3.5 text-amber-400" />
            {isPt ? 'Exemplos rápidos:' : 'Quick samples:'}
          </span>
          {SAMPLE_URLS.map((sample, idx) => (
            <button
              key={idx}
              onClick={() => {
                setInputUrl(sample.url);
                if (sample.url.includes('Cosmos')) {
                  setDisplayName('Cosmos_Laundromat_1080p.mkv');
                } else if (sample.url.includes('Bunny')) {
                  setDisplayName('Big_Buck_Bunny_1080p.mkv');
                } else {
                  setDisplayName('');
                }
              }}
              className="text-xs px-2.5 py-1 rounded-lg bg-slate-800/70 hover:bg-purple-900/30 hover:border-purple-500/30 border border-slate-700/60 text-slate-300 hover:text-purple-200 transition-colors cursor-pointer"
            >
              {isPt ? sample.title : sample.titleEn}
            </button>
          ))}
        </div>

        {/* Optional Display Name */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 pt-1">
          <div>
            <label className="block text-xs font-semibold text-slate-400 mb-1.5">
              {isPt ? 'Nome original do torrent (opcional):' : 'Original Torrent Name (optional):'}
            </label>
            <input
              type="text"
              value={displayName}
              onChange={(e) => setDisplayName(e.target.value)}
              placeholder={parsed.fileName || (isPt ? 'Ex: Filme_1080p.mkv' : 'Ex: Movie_1080p.mkv')}
              className="w-full bg-slate-950/60 border border-slate-800 rounded-lg px-3 py-2 text-sm text-slate-200 placeholder-slate-600 focus:border-purple-500"
            />
          </div>

          <div className="flex items-end">
            <div className="text-xs text-slate-400 bg-slate-950/40 border border-slate-800/80 rounded-lg p-2.5 w-full flex items-center gap-2">
              <Database className="w-4 h-4 text-purple-400 shrink-0" />
              <span>
                {isPt
                  ? 'Motor com suporte a BEP 9 (Metadata Exchange) e exportação de arquivo .torrent Bencoded.'
                  : 'Engine supporting BEP 9 (Metadata Exchange) and genuine Bencoded .torrent output.'}
              </span>
            </div>
          </div>
        </div>

        {/* Tracker config drawer */}
        {showTrackerConfig && (
          <div className="p-4 bg-slate-950 border border-purple-900/30 rounded-xl space-y-3">
            <div className="flex items-center justify-between">
              <span className="text-xs font-semibold text-purple-300">
                {isPt ? 'Trackers BitTorrent Públicos Ativos' : 'Active Public BitTorrent Trackers'}
              </span>
              <button
                onClick={() => setSelectedTrackers(DEFAULT_TRACKERS)}
                className="text-[11px] text-purple-400 hover:underline cursor-pointer"
              >
                {isPt ? 'Restaurar Padrão' : 'Reset Default'}
              </button>
            </div>
            <div className="grid grid-cols-1 md:grid-cols-2 gap-2 text-xs">
              {DEFAULT_TRACKERS.map((tracker, idx) => {
                const isChecked = selectedTrackers.includes(tracker);
                return (
                  <label
                    key={idx}
                    className={`flex items-center gap-2 p-2 rounded-lg border cursor-pointer transition-colors ${
                      isChecked
                        ? 'bg-purple-950/30 border-purple-700/40 text-purple-200'
                        : 'bg-slate-900/60 border-slate-800 text-slate-500'
                    }`}
                  >
                    <input
                      type="checkbox"
                      checked={isChecked}
                      onChange={(e) => {
                        if (e.target.checked) {
                          setSelectedTrackers([...selectedTrackers, tracker]);
                        } else {
                          setSelectedTrackers(selectedTrackers.filter((t) => t !== tracker));
                        }
                      }}
                      className="rounded border-slate-700 text-purple-600 focus:ring-purple-500"
                    />
                    <span className="font-mono truncate">{tracker}</span>
                  </label>
                );
              })}
            </div>
          </div>
        )}
      </div>

      {/* THREE STATES ENGINE PANEL */}
      {parsed.isValid && activeMeta && (
        <div className="border border-slate-800 rounded-2xl bg-slate-950/70 p-6 space-y-6">
          {/* State Stepper Bar */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-800/80">
            <div className="flex items-center gap-3">
              <div
                className={`w-3 h-3 rounded-full ${
                  engineState === 'searching'
                    ? 'bg-amber-400 animate-ping'
                    : engineState === 'metadata_retrieved'
                    ? 'bg-blue-400 animate-pulse'
                    : engineState === 'ready'
                    ? 'bg-emerald-400'
                    : 'bg-rose-400'
                }`}
              />
              <div>
                <span className="text-xs uppercase font-mono font-bold tracking-wider text-slate-400 block">
                  {isPt ? 'Status do Motor de Metadados' : 'Metadata Engine Status'}
                </span>
                <span className="text-base font-bold text-white">
                  {engineState === 'searching' && (isPt ? '1. Searching (Procurando peers & BEP 9)...' : '1. Searching (DHT & BEP 9 peers)...')}
                  {engineState === 'metadata_retrieved' && (isPt ? '2. Metadata Retrieved (Metadados Carregados)' : '2. Metadata Retrieved')}
                  {engineState === 'ready' && (isPt ? '3. Ready (Disponibilizando as Opções)' : '3. Ready (All Options Available)')}
                  {engineState === 'fallback' && (isPt ? 'Alternativa em caso de falha' : 'Fallback Alternative Active')}
                </span>
              </div>
            </div>

            {/* State selector / tester */}
            <div className="flex items-center gap-1.5 bg-slate-900 p-1 rounded-xl border border-slate-800 text-xs">
              <button
                onClick={() => setEngineState('searching')}
                className={`px-2.5 py-1 rounded-lg font-medium transition cursor-pointer ${
                  engineState === 'searching' ? 'bg-amber-500/20 text-amber-300 font-bold' : 'text-slate-400 hover:text-white'
                }`}
              >
                Searching
              </button>
              <button
                onClick={() => setEngineState('metadata_retrieved')}
                className={`px-2.5 py-1 rounded-lg font-medium transition cursor-pointer ${
                  engineState === 'metadata_retrieved' ? 'bg-blue-500/20 text-blue-300 font-bold' : 'text-slate-400 hover:text-white'
                }`}
              >
                Retrieved
              </button>
              <button
                onClick={() => setEngineState('ready')}
                className={`px-2.5 py-1 rounded-lg font-medium transition cursor-pointer ${
                  engineState === 'ready' ? 'bg-emerald-500/20 text-emerald-300 font-bold' : 'text-slate-400 hover:text-white'
                }`}
              >
                Ready
              </button>
              <button
                onClick={handleSimulateFallback}
                className={`px-2.5 py-1 rounded-lg font-medium transition cursor-pointer ${
                  engineState === 'fallback' ? 'bg-rose-500/20 text-rose-300 font-bold' : 'text-slate-400 hover:text-white'
                }`}
              >
                {isPt ? 'Falha / Alternativa' : 'Fallback'}
              </button>
            </div>
          </div>

          {/* STATE 1: SEARCHING BANNER */}
          {engineState === 'searching' && (
            <div className="p-4 bg-amber-950/20 border border-amber-800/40 rounded-xl space-y-3 animate-in fade-in">
              <div className="flex items-center gap-3">
                <RefreshCw className="w-5 h-5 text-amber-400 animate-spin shrink-0" />
                <div>
                  <h4 className="font-semibold text-amber-300 text-sm">
                    {isPt ? 'Procurando peers e solicitando metadados via DHT...' : 'Searching for peers and requesting BEP 9 metadata...'}
                  </h4>
                  <p className="text-xs text-amber-200/70 mt-0.5">
                    {isPt
                      ? 'Consultando nós de bootstrap DHT (router.bittorrent.com, dht.transmissionbt.com) e daemon local do Stremio em 127.0.0.1:11470.'
                      : 'Connecting to DHT bootstrap nodes and Stremio streaming daemon at 127.0.0.1:11470.'}
                  </p>
                </div>
              </div>

              <div className="pt-2 flex flex-wrap gap-2">
                <button
                  onClick={() => setEngineState('ready')}
                  className="px-3 py-1.5 bg-amber-900/40 hover:bg-amber-900/60 border border-amber-700/50 rounded-lg text-xs font-semibold text-amber-200 transition cursor-pointer"
                >
                  {isPt ? 'Acelerar / Pular Pesquisa' : 'Skip & Force Ready'}
                </button>
                <button
                  onClick={handleSimulateFallback}
                  className="px-3 py-1.5 bg-slate-900 hover:bg-slate-850 border border-slate-700 rounded-lg text-xs font-medium text-slate-300 transition cursor-pointer"
                >
                  {isPt ? 'Usar Alternativa do Stream' : 'Use Stream Fallback'}
                </button>
              </div>
            </div>
          )}

          {/* STATE 4: FALLBACK / ALTERNATIVE ON FAILURE */}
          {engineState === 'fallback' && (
            <div className="p-4 bg-rose-950/30 border border-rose-800/50 rounded-xl space-y-3">
              <div className="flex items-start gap-3">
                <ShieldAlert className="w-5 h-5 text-rose-400 shrink-0 mt-0.5" />
                <div className="space-y-1 text-xs">
                  <h4 className="font-bold text-rose-300 text-sm">
                    {isPt ? 'Alternativa em caso de falha na pesquisa DHT:' : 'Fallback activated for DHT lookup failure:'}
                  </h4>
                  <p className="text-rose-200/80 leading-relaxed">
                    {isPt
                      ? 'Se os nós DHT demorarem ou a conexão estiver atrás de CGNAT/firewall restritivo, o Magnet Bridge não fica travado: ele sintetiza a estrutura do .torrent diretamente com base nas informações do fluxo do Stremio!'
                      : 'If DHT peers do not respond or network restricts UDP, Magnet Bridge generates the .torrent file from Stremio stream headers without blocking.'}
                  </p>
                </div>
              </div>

              <div className="pt-2 flex flex-wrap gap-2">
                <button
                  onClick={handleDownloadRealDotTorrent}
                  className="flex items-center gap-1.5 px-3.5 py-2 bg-emerald-600 hover:bg-emerald-500 text-white rounded-lg text-xs font-semibold shadow-md transition cursor-pointer"
                >
                  <Download className="w-3.5 h-3.5" />
                  <span>{isPt ? 'Salvar .torrent com Dados Alternativos' : 'Save .torrent via Fallback Data'}</span>
                </button>

                <button
                  onClick={handleRetryLookup}
                  className="flex items-center gap-1.5 px-3 py-2 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg text-xs font-medium transition cursor-pointer"
                >
                  <RefreshCw className="w-3.5 h-3.5 text-purple-400" />
                  <span>{isPt ? 'Tentar Pesquisa DHT Novamente' : 'Retry DHT Search'}</span>
                </button>
              </div>
            </div>
          )}

          {/* STATE 2 & 3: METADATA DETAILS DISPLAY */}
          {(engineState === 'metadata_retrieved' || engineState === 'ready' || engineState === 'fallback') && (
            <div className="space-y-6 animate-in fade-in duration-300">
              {/* Torrent High-Level Overview Grid */}
              <div className="grid grid-cols-1 md:grid-cols-4 gap-3 text-xs">
                {/* Name */}
                <div className="p-3 bg-slate-900/80 rounded-xl border border-slate-800 md:col-span-2">
                  <span className="text-slate-400 block text-[10px] uppercase font-bold tracking-wider mb-1">
                    {isPt ? 'Nome Original do Torrent' : 'Original Torrent Name'}
                  </span>
                  <div className="font-bold text-slate-100 text-sm truncate" title={activeMeta.name}>
                    {activeMeta.name}
                  </div>
                  <span className="text-[11px] text-purple-400 mt-1 block font-mono">
                    {activeMeta.retrievalSource}
                  </span>
                </div>

                {/* Total Size */}
                <div className="p-3 bg-slate-900/80 rounded-xl border border-slate-800">
                  <span className="text-slate-400 block text-[10px] uppercase font-bold tracking-wider mb-1 flex items-center gap-1">
                    <HardDrive className="w-3.5 h-3.5 text-purple-400" />
                    <span>{isPt ? 'Tamanho Total' : 'Total Size'}</span>
                  </span>
                  <span className="font-bold text-emerald-400 text-base font-mono">
                    {formatBytes(activeMeta.totalSize)}
                  </span>
                  <span className="text-[10px] text-slate-500 block mt-0.5">
                    {activeMeta.totalSize.toLocaleString()} bytes
                  </span>
                </div>

                {/* Pieces */}
                <div className="p-3 bg-slate-900/80 rounded-xl border border-slate-800">
                  <span className="text-slate-400 block text-[10px] uppercase font-bold tracking-wider mb-1 flex items-center gap-1">
                    <Layers className="w-3.5 h-3.5 text-blue-400" />
                    <span>{isPt ? 'Peças & Tamanho' : 'Pieces & Length'}</span>
                  </span>
                  <span className="font-bold text-blue-300 text-base font-mono">
                    {activeMeta.pieceCount} peças
                  </span>
                  <span className="text-[10px] text-slate-400 block mt-0.5 font-mono">
                    {formatBytes(activeMeta.pieceLength)} por peça
                  </span>
                </div>
              </div>

              {/* InfoHash Bar */}
              <div className="p-3.5 bg-slate-900/90 rounded-xl border border-slate-800 flex flex-col sm:flex-row sm:items-center justify-between gap-2 text-xs">
                <div className="flex items-center gap-2 truncate">
                  <Hash className="w-4 h-4 text-purple-400 shrink-0" />
                  <span className="font-bold text-slate-300">InfoHash v1 (SHA-1):</span>
                  <span className="font-mono text-purple-300 truncate selection:bg-purple-500 selection:text-white">
                    {activeMeta.infoHash}
                  </span>
                </div>
                <button
                  onClick={() => copyToClipboard(activeMeta.infoHash, 'hash-btn')}
                  className="text-purple-400 hover:text-purple-300 font-medium px-2 py-1 rounded bg-slate-800 shrink-0 cursor-pointer text-[11px]"
                >
                  {copiedField === 'hash-btn' ? (isPt ? 'Copiado!' : 'Copied!') : (isPt ? 'Copiar Hash' : 'Copy Hash')}
                </button>
              </div>

              {/* Complete File List with Individual Sizes */}
              <div className="bg-slate-900/90 rounded-xl border border-slate-800 p-4 space-y-3">
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-2">
                    <FolderTree className="w-4 h-4 text-purple-400" />
                    <h4 className="font-bold text-white text-xs uppercase tracking-wider">
                      {isPt ? 'Lista Completa dos Arquivos' : 'Complete File Breakdown'} ({activeMeta.files.length})
                    </h4>
                  </div>
                  <span className="text-[11px] text-slate-400 font-mono">
                    {isPt ? 'Tamanho individual com integridade' : 'Individual size verification'}
                  </span>
                </div>

                <div className="space-y-2 max-h-56 overflow-y-auto pr-1">
                  {activeMeta.files.map((file, i) => {
                    const percentage = Math.max(1, Math.round((file.size / activeMeta.totalSize) * 100));
                    return (
                      <div
                        key={i}
                        className="p-2.5 bg-slate-950/80 rounded-lg border border-slate-800/80 hover:border-slate-700 transition space-y-1.5"
                      >
                        <div className="flex items-center justify-between gap-2 text-xs">
                          <span className="font-mono text-slate-200 truncate flex items-center gap-2">
                            <span className="text-slate-500 text-[10px]">{i + 1}.</span>
                            <span className="truncate">{file.path}</span>
                          </span>
                          <span className="font-mono text-emerald-400 font-semibold shrink-0">
                            {formatBytes(file.size)}
                          </span>
                        </div>
                        {/* Progress Bar of file size */}
                        <div className="w-full h-1 bg-slate-800 rounded-full overflow-hidden">
                          <div
                            className="h-full bg-gradient-to-r from-purple-500 to-indigo-500 rounded-full"
                            style={{ width: `${percentage}%` }}
                          />
                        </div>
                      </div>
                    );
                  })}
                </div>
              </div>

              {/* Trackers found in metadata or source */}
              <div className="bg-slate-900/70 rounded-xl border border-slate-800 p-4 space-y-2">
                <div className="flex items-center justify-between">
                  <span className="text-xs font-bold text-slate-300 uppercase tracking-wider flex items-center gap-1.5">
                    <Radio className="w-3.5 h-3.5 text-purple-400" />
                    <span>{isPt ? 'Trackers Encontrados nos Metadados / Origem' : 'Trackers Found in Metadata / Source'}</span>
                  </span>
                  <span className="text-[11px] font-mono text-purple-400">
                    {activeMeta.trackers.length} {isPt ? 'anunciadores' : 'announcers'}
                  </span>
                </div>
                <div className="font-mono text-[11px] text-slate-400 space-y-1 max-h-24 overflow-y-auto bg-slate-950 p-2.5 rounded-lg border border-slate-800">
                  {activeMeta.trackers.map((tr, idx) => (
                    <div key={idx} className="truncate text-slate-300">
                      • {tr}
                    </div>
                  ))}
                </div>
              </div>

              {/* STATE 3: READY ACTIONS (TWO MAIN OPTIONS + EXTRAS) */}
              <div className="pt-2 space-y-3">
                <div className="text-xs font-bold uppercase tracking-wider text-emerald-400 flex items-center gap-1.5">
                  <Check className="w-4 h-4 text-emerald-400" />
                  <span>
                    {isPt
                      ? 'Opções Disponíveis para Uso Imediato:'
                      : 'Available Options for Immediate Use:'}
                  </span>
                </div>

                <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
                  {/* Option 1: Save Real .torrent File */}
                  <button
                    onClick={handleDownloadRealDotTorrent}
                    className="flex items-center justify-center gap-2.5 px-5 py-4 bg-gradient-to-r from-emerald-600 to-teal-600 hover:from-emerald-500 hover:to-teal-500 text-white font-bold rounded-xl text-sm shadow-xl shadow-emerald-600/25 transition-all text-center cursor-pointer hover:-translate-y-0.5"
                  >
                    <Download className="w-5 h-5" />
                    <span>{isPt ? 'Gerar & Baixar Arquivo .torrent' : 'Generate & Save .torrent File'}</span>
                    <span className="text-[10px] bg-black/20 px-2 py-0.5 rounded font-mono uppercase">
                      Bencode BEP 3
                    </span>
                  </button>

                  {/* Option 2: Open Magnet in Client */}
                  <a
                    href={parsed.magnetUri!}
                    className="flex items-center justify-center gap-2.5 px-5 py-4 bg-gradient-to-r from-purple-600 to-indigo-600 hover:from-purple-500 hover:to-indigo-500 text-white font-bold rounded-xl text-sm shadow-xl shadow-purple-600/25 transition-all text-center"
                  >
                    <ExternalLink className="w-5 h-5" />
                    <span>{isPt ? 'Abrir no Cliente de Torrent (Magnet)' : 'Open in Torrent Client (Magnet)'}</span>
                  </a>
                </div>

                {/* Sub-actions Row */}
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-2 pt-1 text-xs">
                  <button
                    onClick={() => copyToClipboard(parsed.magnetUri!, 'sub-magnet')}
                    className="flex items-center justify-center gap-1.5 p-2.5 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg border border-slate-700 transition cursor-pointer"
                  >
                    {copiedField === 'sub-magnet' ? (
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                    ) : (
                      <Copy className="w-3.5 h-3.5 text-purple-400" />
                    )}
                    <span>{isPt ? 'Copiar Magnet Completo' : 'Copy Full Magnet'}</span>
                  </button>

                  <button
                    onClick={() => setShowQrModal(true)}
                    className="flex items-center justify-center gap-1.5 p-2.5 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg border border-slate-700 transition cursor-pointer"
                  >
                    <QrCode className="w-3.5 h-3.5 text-indigo-400" />
                    <span>{isPt ? 'QR Code para Celular/TV' : 'Scan QR for Phone/TV'}</span>
                  </button>

                  <button
                    onClick={handleSimulateFallback}
                    className="flex items-center justify-center gap-1.5 p-2.5 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg border border-slate-700 transition cursor-pointer"
                  >
                    <ShieldAlert className="w-3.5 h-3.5 text-amber-400" />
                    <span>{isPt ? 'Ver Alternativa de Falha' : 'Test Fallback Route'}</span>
                  </button>
                </div>
              </div>
            </div>
          )}
        </div>
      )}

      {/* Invalid input alert */}
      {!parsed.isValid && inputUrl && (
        <div className="p-4 bg-rose-950/30 border border-rose-900/50 rounded-xl flex items-start gap-3">
          <AlertCircle className="w-5 h-5 text-rose-400 shrink-0 mt-0.5" />
          <div className="text-sm">
            <p className="font-semibold text-rose-300">
              {isPt ? 'Link inválido ou não reconhecido' : 'Invalid or Unrecognized Stream Link'}
            </p>
            <p className="text-rose-400/80 text-xs mt-1">
              {parsed.errorMessage ||
                (isPt
                  ? 'Verifique se o link possui um hash BitTorrent de 40 dígitos hexadecimais.'
                  : 'Verify that the URL contains a 40-character hex torrent infohash.')}
            </p>
          </div>
        </div>
      )}

      {/* QR Code Modal */}
      {showQrModal && qrCodeDataUrl && (
        <div className="fixed inset-0 z-50 bg-black/80 backdrop-blur-sm flex items-center justify-center p-4">
          <div className="bg-slate-900 border border-slate-700 rounded-2xl p-6 max-w-sm w-full shadow-2xl text-center">
            <h3 className="text-lg font-bold text-white mb-1">
              {isPt ? 'Escanear Magnet Link' : 'Scan Magnet Link'}
            </h3>
            <p className="text-xs text-slate-400 mb-4">
              {isPt
                ? 'Aponte a câmera do celular ou leitor da Android TV para abrir o torrent direto no dispositivo.'
                : 'Point your phone or Android TV camera to open the torrent directly on device.'}
            </p>

            <div className="bg-white p-4 rounded-xl inline-block shadow-inner">
              <img src={qrCodeDataUrl} alt="Magnet QR Code" className="w-64 h-64 mx-auto" />
            </div>

            <div className="mt-4 p-2 bg-slate-950 rounded-lg text-xs font-mono text-slate-400 truncate">
              {parsed.infoHash}
            </div>

            <div className="mt-5 flex gap-3">
              <button
                onClick={() => copyToClipboard(parsed.magnetUri!, 'qr-modal')}
                className="flex-1 py-2 px-3 bg-purple-600 hover:bg-purple-500 text-white rounded-lg text-xs font-semibold transition cursor-pointer"
              >
                {copiedField === 'qr-modal' ? (isPt ? 'Copiado!' : 'Copied!') : (isPt ? 'Copiar Magnet' : 'Copy Magnet')}
              </button>
              <button
                onClick={() => setShowQrModal(false)}
                className="flex-1 py-2 px-3 bg-slate-800 hover:bg-slate-700 text-slate-300 rounded-lg text-xs font-semibold transition cursor-pointer"
              >
                {isPt ? 'Fechar' : 'Close'}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
