package com.stremiomagnetbridge.app;

import java.io.IOException;
import java.security.MessageDigest;
import java.util.*;

public class TorrentMetadata {
    public enum State {
        SEARCHING,
        METADATA_RETRIEVED,
        READY,
        FALLBACK
    }

    public static class FileItem {
        public String name;
        public String path;
        public long size;

        public FileItem(String name, String path, long size) {
            this.name = name;
            this.path = path;
            this.size = size;
        }

        public String getFormattedSize() {
            if (size < 1024) return size + " B";
            if (size < 1024 * 1024) return String.format(Locale.US, "%.1f KB", size / 1024.0);
            if (size < 1024 * 1024 * 1024) return String.format(Locale.US, "%.2f MB", size / (1024.0 * 1024.0));
            return String.format(Locale.US, "%.2f GB", size / (1024.0 * 1024.0 * 1024.0));
        }
    }

    public String infoHash;
    public String name;
    public long totalSize;
    public long pieceLength = 2097152; // Default 2MB per piece
    public int pieceCount = 1;
    public List<FileItem> files = new ArrayList<FileItem>();
    public List<String> trackers = new ArrayList<String>();
    public State state = State.SEARCHING;
    public String statusMessage = "Procurando peers e solicitando metadados via DHT (BEP 9)...";
    public String retrievalSource = "DHT / BEP 9 Swarm";
    public byte[] piecesHashes; // SHA-1 per piece (20 bytes each)

    public TorrentMetadata(String infoHash) {
        this.infoHash = infoHash.toLowerCase();
        this.trackers.add("udp://tracker.opentrackr.org:1337/announce");
        this.trackers.add("udp://open.stealth.si:80/announce");
        this.trackers.add("udp://tracker.torrent.eu.org:451/announce");
        this.trackers.add("udp://explodie.org:6969/announce");
    }

    public String getFormattedTotalSize() {
        if (totalSize < 1024) return totalSize + " B";
        if (totalSize < 1024 * 1024) return String.format(Locale.US, "%.1f KB", totalSize / 1024.0);
        if (totalSize < 1024 * 1024 * 1024) return String.format(Locale.US, "%.2f MB", totalSize / (1024.0 * 1024.0));
        return String.format(Locale.US, "%.2f GB", totalSize / (1024.0 * 1024.0 * 1024.0));
    }

    public String getFormattedPieceLength() {
        if (pieceLength < 1024 * 1024) return (pieceLength / 1024) + " KB";
        return (pieceLength / (1024 * 1024)) + " MB";
    }

    public byte[] buildDotTorrentBytes() throws IOException {
        Map<String, Object> torrent = new LinkedHashMap<String, Object>();
        
        String primaryTracker = trackers.isEmpty() ? "udp://tracker.opentrackr.org:1337/announce" : trackers.get(0);
        torrent.put("announce", primaryTracker);

        List<List<String>> announceList = new ArrayList<List<String>>();
        for (String tr : trackers) {
            announceList.add(Collections.singletonList(tr));
        }
        torrent.put("announce-list", announceList);
        torrent.put("comment", "Generated by MagnetBridge v0.8 for Stremio");
        torrent.put("created by", "MagnetBridge/0.8 (Android)");
        torrent.put("creation date", System.currentTimeMillis() / 1000L);

        Map<String, Object> info = new LinkedHashMap<String, Object>();
        info.put("name", (name == null || name.trim().isEmpty()) ? "Stremio_" + infoHash.substring(0, 8) : name);
        info.put("piece length", pieceLength);

        // Ensure piece count and piece hashes
        if (piecesHashes == null || piecesHashes.length != pieceCount * 20) {
            piecesHashes = generatePlaceholderPiecesHashes(pieceCount, infoHash);
        }
        info.put("pieces", piecesHashes);

        if (files.size() <= 1) {
            long len = totalSize > 0 ? totalSize : (files.isEmpty() ? 104857600L : files.get(0).size);
            info.put("length", len);
        } else {
            List<Map<String, Object>> filesList = new ArrayList<Map<String, Object>>();
            for (FileItem f : files) {
                Map<String, Object> fMap = new LinkedHashMap<String, Object>();
                fMap.put("length", f.size);
                List<String> pathTokens = new ArrayList<String>();
                for (String p : f.path.split("/")) {
                    if (!p.trim().isEmpty()) pathTokens.add(p);
                }
                if (pathTokens.isEmpty()) pathTokens.add(f.name);
                fMap.put("path", pathTokens);
                filesList.add(fMap);
            }
            info.put("files", filesList);
        }

        torrent.put("info", info);
        return BencodeEncoder.encode(torrent);
    }

    private static byte[] generatePlaceholderPiecesHashes(int count, String hashSeed) {
        byte[] result = new byte[count * 20];
        try {
            MessageDigest md = MessageDigest.getInstance("SHA-1");
            byte[] seed = hashSeed.getBytes("UTF-8");
            for (int i = 0; i < count; i++) {
                md.update(seed);
                md.update((byte) (i & 0xFF));
                md.update((byte) ((i >> 8) & 0xFF));
                byte[] piece = md.digest();
                System.arraycopy(piece, 0, result, i * 20, 20);
            }
        } catch (Exception ignored) {
        }
        return result;
    }
}
